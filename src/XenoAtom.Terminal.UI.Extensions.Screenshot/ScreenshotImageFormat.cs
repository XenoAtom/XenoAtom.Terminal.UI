namespace XenoAtom.Terminal.UI.Extensions.Screenshot;

/// <summary>
/// Specifies the encoded image format used for screenshot export.
/// </summary>
public enum ScreenshotImageFormat
{
    /// <summary>
    /// Encodes the screenshot as PNG.
    /// </summary>
    Png,

    /// <summary>
    /// Encodes the screenshot as JPEG.
    /// </summary>
    Jpeg,

    /// <summary>
    /// Encodes the screenshot as WebP.
    /// </summary>
    Webp,
}
