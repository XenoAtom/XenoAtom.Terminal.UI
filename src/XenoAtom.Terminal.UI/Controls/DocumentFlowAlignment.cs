namespace XenoAtom.Terminal.UI.Controls;

/// <summary>
/// Specifies horizontal alignment for a document item within <see cref="DocumentFlow"/>.
/// </summary>
public enum DocumentFlowAlignment
{
    /// <summary>Aligns the item to the left edge.</summary>
    Left,

    /// <summary>Aligns the item to the right edge.</summary>
    Right,

    /// <summary>Centers the item horizontally.</summary>
    Center,

    /// <summary>Stretches the item to the available width.</summary>
    Stretch,
}
