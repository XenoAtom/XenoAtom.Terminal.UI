namespace XenoAtom.Terminal.UI;

/// <summary>
/// Specifies how a visual is aligned vertically within its parent.
/// </summary>
public enum VerticalAlignment
{
    /// <summary>
    /// Align to the top.
    /// </summary>
    Top = 0,
    /// <summary>
    /// Center vertically.
    /// </summary>
    Center = 1,
    /// <summary>
    /// Align to the bottom.
    /// </summary>
    Bottom = 2,
    /// <summary>
    /// Stretch to fill the available height.
    /// </summary>
    Stretch = 3,
}
